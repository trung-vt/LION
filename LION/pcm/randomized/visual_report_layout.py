"""Refresh the two existing LaTeX visual appendices from saved PCM figures.

One generator controls BOTH paper and slide ordering, avoiding duplicated
hand-written figure lists. No model inference, acquisition, metrics, or
training runs occur here. Reconstruction figures and their absolute-error
figures are adjacent for every test condition.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil

from LION.pcm.randomized.unseen_analysis import SCENARIO_LABELS

RATES = (10, 20, 50)
SCENARIOS = ("noiseless", "gaussian_dark", "pcm_default_10ms", "pcm_short_100us")
CELLS = ((0, "CIGS"), (1, "Perovskite centre"))
ADDITIONAL_METRICS = (
    "psnr_vs_sampling_noiseless.png",
    "psnr_vs_sampling_gaussian_dark.png",
    "ssim_vs_sampling_noiseless.png",
    "ssim_vs_sampling_gaussian_dark.png",
    "ssim_vs_sampling_pcm_default_10ms.png",
    "ssim_vs_sampling_pcm_short_100us.png",
    "psnr_20pct_pcm_default_10ms.png",
    "psnr_20pct_pcm_short_100us.png",
    "noise_rms_vs_sampling.png",
)


def presentation_figures(source: Path, paper: Path, slides: Path) -> dict:
    """Validate all sources before touching existing figure and TeX outputs."""
    images = source / "complete_image_archive" / "montages"
    plots = source / "analysis" / "figures"
    required = {
        "normalized_source_pair.png": plots / "normalized_source_pair.png",
        **{name: plots / name for name in ADDITIONAL_METRICS},
        "psnr_vs_sampling_pcm_default_10ms.png": plots
        / "psnr_vs_sampling_pcm_default_10ms.png",
        "psnr_vs_sampling_pcm_short_100us.png": plots
        / "psnr_vs_sampling_pcm_short_100us.png",
    }
    names = []
    for rate in RATES:
        for scenario in SCENARIOS:
            for index, _ in CELLS:
                prefix = f"case_{index:02d}_r{rate:03d}_{scenario}"
                for suffix in ("_recon.png", "_abs_error.png"):
                    name = prefix + suffix
                    required[name] = images / name
                    names.append(name)
    if len(names) != 48 or len(set(names)) != 48:
        raise AssertionError("Incomplete fixed reconstruction/error conditions")
    absent = [str(path) for path in required.values() if not path.is_file()]
    if absent:
        raise FileNotFoundError("Missing figures:\n" + "\n".join(absent))
    for destination in (paper, slides):
        (destination / "figures").mkdir(parents=True, exist_ok=True)
        for name, path in required.items():
            output = destination / "figures" / name
            # Known generated images are intentionally updated; never touch
            # unrelated files in either LaTeX repository.
            if not output.is_file() or output.read_bytes() != path.read_bytes():
                shutil.copyfile(path, output)

    paper_lines = [
        "% Generated by LION/pcm/randomized/visual_report_layout.py.",
        "% Figures are generated from existing float32 test reconstructions.",
        r"\clearpage",
        r"\appendix",
        r"\section{Additional numerical plots}",
        "These plots summarize the same saved 216 reconstructions; "
        "no reconstruction was recomputed for this display-only revision.",
    ]
    for path in ADDITIONAL_METRICS:
        title = path.removesuffix(".png").replace("_", " ")
        paper_lines.extend(
            [
                r"\begin{figure}[p]",
                r"\centering",
                rf"\includegraphics[width=.95\linewidth,height=.73\textheight,keepaspectratio]{{{path}}}",
                rf"\caption{{Fixed-test numerical figure: {title}. Original metric values are unchanged.}}",
                r"\end{figure}",
                r"\clearpage",
            ]
        )
    paper_lines.extend(
        [
            r"\section{Reconstructions and absolute errors paired by test condition}",
            "For each fixed sampling/noise setting, the reconstruction figure is "
            "immediately followed by its absolute-error figure. Both show CIGS above "
            "the perovskite centre crop and all nine methods in the same positions. "
            "Error maps use viridis on the shared transformed-scale interval "
            "$[0,0.5]$; reconstruction images use AFM hot on $[0,1]$. "
            "The two-line method labels and common colorbar are included in each panel.",
        ]
    )

    slides_lines = [
        "% Generated by LION/pcm/randomized/visual_report_layout.py.",
        "% Reconstruction and corresponding absolute error are adjacent.",
        r"\section{Additional numerical plots}",
    ]
    for name in ADDITIONAL_METRICS:
        heading = name.removesuffix(".png").replace("_", " ")
        slides_lines += _beamer_frame(
            f"Numerical results: {heading}",
            name,
        )
    slides_lines += [
        r"\section{Reconstruction and absolute-error pairs}",
    ]
    for rate in RATES:
        for scenario in SCENARIOS:
            label = SCENARIO_LABELS[scenario]
            for kind, title_kind in (
                ("recon", "Reconstruction"),
                ("abs_error", "Absolute error"),
            ):
                pair = [
                    f"case_{index:02d}_r{rate:03d}_{scenario}_{kind}.png"
                    for index, _ in CELLS
                ]
                caption = (
                    f"{title_kind} for CIGS (above) and the perovskite centre "
                    f"(below), {rate}\\% sampling, {label}. "
                    "Each image contains its method labels, PSNR/SSIM values "
                    "and a common colorbar."
                )
                paper_lines += [
                    r"\begin{figure}[p]",
                    r"\centering",
                    rf"\includegraphics[width=.96\linewidth,height=.33\textheight,keepaspectratio]{{{pair[0]}}}",
                    r"\par\vspace{7mm}",
                    rf"\includegraphics[width=.96\linewidth,height=.33\textheight,keepaspectratio]{{{pair[1]}}}",
                    r"\par\vspace{5mm}",
                    rf"\caption{{{caption}}}",
                    r"\end{figure}",
                    r"\clearpage",
                ]
            for case_index, case_label in CELLS:
                basename = f"case_{case_index:02d}_r{rate:03d}_{scenario}"
                # Always put each error frame immediately AFTER its own recon.
                slides_lines += _beamer_frame(
                    f"{case_label}: {rate}\\%, {label} -- reconstruction",
                    basename + "_recon.png",
                )
                slides_lines += _beamer_frame(
                    f"{case_label}: {rate}\\%, {label} -- absolute error",
                    basename + "_abs_error.png",
                )
    appendix = paper / "complete_visual_appendix.tex"
    frames = slides / "complete_visual_frames.tex"
    appendix.write_text("\n".join(paper_lines) + "\n", encoding="utf-8")
    frames.write_text("\n".join(slides_lines) + "\n", encoding="utf-8")
    return {
        "copied_figures_to_each_repo": len(required),
        "paper_appendix_reconstruction_error_pairs": 12,
        "slide_backup_reconstruction_error_pairs": 24,
        "slide_backup_plot_frames": len(ADDITIONAL_METRICS),
        "slide_backup_image_frames": 48,
        "paper_fragment": str(appendix),
        "slides_fragment": str(frames),
    }


def _beamer_frame(title: str, filename: str) -> list[str]:
    return [
        rf"\begin{{frame}}[t]{{{title}}}",
        r"\centering",
        r"\vspace*{2mm}",
        rf"\includegraphics[width=.99\textwidth,height=.69\textheight,keepaspectratio]{{{filename}}}",
        r"\end{frame}",
    ]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", type=Path, required=True)
    p.add_argument("--paper", type=Path, required=True)
    p.add_argument("--slides", type=Path, required=True)
    a = p.parse_args()
    print(presentation_figures(a.source, a.paper, a.slides))


if __name__ == "__main__":
    main()
